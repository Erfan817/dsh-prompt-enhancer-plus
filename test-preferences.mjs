import assert from 'node:assert/strict';
import { PreferenceLibrary, PREFERENCE_DOMAIN, projectKey, parsePreference } from './preferences.js';
import { PromptEnhancerService, enhancerTool } from './index.js';
import { PersonaLibrary, PERSONA_DOMAIN } from './personas.js';
const storage = (initial) => {
  let state = structuredClone(initial), writes = 0;
  return { get: () => state, set: async next => { state = structuredClone(next); writes++; }, get writes() { return writes; } };
};
const global = storage(PREFERENCE_DOMAIN.global.initial);
const library = new PreferenceLibrary(global);
const a = { sessionId: 'a', cwd: 'D:\\Project' }, b = { sessionId: 'b', cwd: 'd:/project/' }, c = { sessionId: 'c', cwd: 'D:\\Other' };
assert.equal(projectKey(a.cwd), projectKey(b.cwd));
const save = (text, scope, context, extra = {}) => library.mutate({ action: 'confirm', text, scope, expectedRevision: global.get().revision, ...extra }, context, true);
await save('Keep prompts brief.', 'project', a);
assert.equal(library.list(b).rules.length, 1);
assert.equal(library.list(c).rules.length, 0);
assert.equal(new PreferenceLibrary(global).list(a).rules.length, 1);
await assert.rejects(save('Use detailed prose.', 'session', a), { code: 'preference-choice' });
assert.equal(global.writes, 1);
await save('Use detailed prose.', 'session', a, { resolution: 'replace' });
assert.equal(library.list(b).rules.length, 1);
assert.equal(library.list(a).rules.length, 2);
assert.deepEqual(library.list(a).rules.filter(item => item.active).map(item => item.text), ['Use detailed prose.']);
assert.equal(library.list(b).rules[0].text, 'Keep prompts brief.');
await save('Avoid decorative formatting.', 'global', c);
assert.equal(library.list(b).rules.length, 2);
const rev = global.get().revision;
const id = library.list(c).rules[0].id;
const outcomes = await Promise.allSettled([1, 2].map(() => library.mutate({ action: 'delete-preference', id, expectedRevision: rev }, c)));
assert.equal(outcomes.filter(r => r.status === 'fulfilled').length, 1);
assert.equal(outcomes.find(r => r.status === 'rejected').reason.code, 'preference-conflict');
await assert.rejects(library.mutate({ action: 'confirm', expectedRevision: global.get().revision, text: 'x' }, a), { code: 'preference-user-only' });
assert.equal(parsePreference('{"preference":""}'), '');
assert.throws(() => parsePreference('{"preference":2}'));

const scopedStorage = storage(PREFERENCE_DOMAIN.global.initial);
const scopedLibrary = new PreferenceLibrary(scopedStorage);
const saveScoped = (text, scope, context) => scopedLibrary.mutate({ action: 'confirm', text, scope, resolution: 'replace', expectedRevision: scopedStorage.get().revision }, context, true);
const activeTexts = context => scopedLibrary.list(context).rules.filter(item => item.active).map(item => item.text);
await saveScoped('Global style.', 'global', a);
const globalId = scopedStorage.get().rules[0].id;
await saveScoped('Project style.', 'project', a);
assert.deepEqual(activeTexts(a), ['Project style.']);
assert.deepEqual(activeTexts(b), ['Project style.']);
assert.deepEqual(activeTexts(c), ['Global style.']);
assert.ok(scopedStorage.get().rules.some(item => item.id === globalId));
await saveScoped('Session style.', 'session', a);
assert.deepEqual(activeTexts(a), ['Session style.']);
assert.deepEqual(activeTexts(b), ['Project style.']);
assert.deepEqual(activeTexts(c), ['Global style.']);
await saveScoped('Updated session style.', 'session', a);
assert.equal(scopedStorage.get().rules.length, 3);
assert.deepEqual(activeTexts(a), ['Updated session style.']);
assert.deepEqual(new PreferenceLibrary(scopedStorage).list(c).rules.filter(item => item.active).map(item => item.text), ['Global style.']);
const sessionRule = scopedLibrary.list(a).rules.find(item => item.scope === 'session');
await scopedLibrary.mutate({ action: 'delete-preference', id: sessionRule.id, expectedRevision: scopedStorage.get().revision }, a);
assert.deepEqual(activeTexts(a), ['Project style.']);
const projectRule = scopedLibrary.list(a).rules.find(item => item.scope === 'project');
await assert.rejects(scopedLibrary.mutate({ action: 'delete-preference', id: projectRule.id, expectedRevision: scopedStorage.get().revision }, c), { code: 'preference-missing' });
await scopedLibrary.mutate({ action: 'delete-preference', id: projectRule.id, expectedRevision: scopedStorage.get().revision }, a);
assert.deepEqual(activeTexts(a), ['Global style.']);
const queuedAbort = new AbortController();
const cancelledSave = scopedLibrary.mutate({ action: 'confirm', text: 'Never saved.', expectedRevision: scopedStorage.get().revision }, a, true, () => queuedAbort.signal.throwIfAborted());
queuedAbort.abort();
await assert.rejects(cancelledSave);
assert.deepEqual(activeTexts(a), ['Global style.']);

const systems = [];
let cwd = a.cwd;
const ctx = {
  agents: { get: () => ({ session: {} }) }, workingDirectory: { get: () => cwd },
  agentDefaultModel: { currentSelection: () => ({ provider: 'test', model: 'test' }) },
  llm: { prepareCall: async () => ({ config: {}, async *stream(request) {
    systems.push(request.system);
    yield { type: 'text-delta', text: request.system.includes('Compare a generated') ? '{"preference":"Prefer short paragraphs."}' : 'Task: Write a report. Requirements: Keep it useful.' };
    yield { type: 'finish', reason: { kind: 'stop' } };
  } }) },
};
const fresh = storage(PREFERENCE_DOMAIN.global.initial);
const service = new PromptEnhancerService(ctx, { maxInputChars: 12000, timeoutMs: 1000 }, new PersonaLibrary(storage(PERSONA_DOMAIN.global.initial)), new PreferenceLibrary(fresh));
const result = await service.enhance({ text: 'Write a report', sessionId: 'a' });
const inference = { action: 'infer', baselineId: result.baselineId, text: result.enhanced + ' Use short paragraphs.', sessionId: 'a' };
const proposal = await service.preferenceAction(inference, undefined, true);
assert.equal(fresh.writes, 0, 'review/cancel has no durable write');
await assert.rejects(service.perform({ ...inference }), { code: 'preference-user-only' });
assert.ok(!enhancerTool(service).parameters.properties.action.enum.includes('confirm'));
await assert.rejects(service.preferenceAction({ ...inference, sessionId: 'b' }, undefined, true), { code: 'preference-baseline' });
cwd = c.cwd;
await assert.rejects(service.preferenceAction(inference, undefined, true), { code: 'preference-baseline' });
cwd = a.cwd;
await service.preferenceAction({ action: 'confirm', sessionId: 'a', proposalId: proposal.proposalId, text: proposal.text, expectedRevision: proposal.revision, scope: 'project' }, undefined, true);
await service.enhance({ text: 'Write a report', sessionId: 'a' });
assert.ok(systems.at(-1).includes('Prefer short paragraphs.'));
await service.enhance({ text: 'Another task', sessionId: 'b' });
assert.ok(systems.at(-1).includes('Prefer short paragraphs.'));
cwd = c.cwd;
await service.enhance({ text: 'Another task', sessionId: 'b' });
assert.ok(!systems.at(-1).includes('Prefer short paragraphs.'));
const listed = await enhancerTool(service).execute({ action: 'list-preferences' }, { agent: { id: 'b' } });
assert.equal(listed.rules.length, 0);
cwd = a.cwd;
const own = await service.perform({ action: 'list-preferences', sessionId: 'a' });
await enhancerTool(service).execute({ action: 'delete-preference', id: own.rules[0].id, expectedRevision: own.revision }, { agent: { id: 'a' } });
assert.equal(fresh.get().rules.length, 0);
const failing = { get: () => ({ revision: 0, rules: [] }), set: async () => { throw new Error('disk full'); } };
const failedLibrary = new PreferenceLibrary(failing);
await assert.rejects(failedLibrary.mutate({ action: 'confirm', text: 'Brief.', scope: 'project', expectedRevision: 0 }, a, true), /disk full/);
assert.equal(failedLibrary.list(a).revision, 0);
assert.equal(failedLibrary.list(a).rules.length, 0);
const aborted = new AbortController(); aborted.abort();
await assert.rejects(service.preferenceAction(inference, aborted.signal, true));
assert.equal(fresh.get().rules.length, 0);
const scopedService = new PromptEnhancerService(ctx, { maxInputChars: 12000, timeoutMs: 1000 }, new PersonaLibrary(storage(PERSONA_DOMAIN.global.initial)), scopedLibrary);
await saveScoped('Project-only style.', 'project', a);
cwd = a.cwd;
await scopedService.enhance({ text: 'Write a report', sessionId: 'a' });
assert.ok(systems.at(-1).includes('Project-only style.'));
assert.ok(!systems.at(-1).includes('Global style.'));
cwd = c.cwd;
await scopedService.enhance({ text: 'Write a report', sessionId: 'c' });
assert.ok(systems.at(-1).includes('Global style.'));
assert.ok(!systems.at(-1).includes('Project-only style.'));
await saveScoped('New global style.', 'global', a);
assert.ok(scopedStorage.get().rules.some(item => item.text === 'Project-only style.'), 'global saves retain project records');
assert.deepEqual(activeTexts(a), ['New global style.']);
const latestGlobal = scopedStorage.get().rules.find(item => item.scope === 'global');
await scopedLibrary.mutate({ action: 'delete-preference', id: latestGlobal.id, expectedRevision: scopedStorage.get().revision }, c);
assert.deepEqual(activeTexts(a), ['Project-only style.']);
console.log('preference tests passed: scopes, restart, concurrency, conflict, review authority, context binding and immediate application');
